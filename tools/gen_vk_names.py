#!/usr/bin/env python3
"""Every Vulkan command name, for the synthetic libvulkan.so.1 (runtime/linux/).

A Linux guest binds vk* through its own dynamic loader, which resolves symbols
only against ELF objects — so the host's Vulkan has to be presented as one, and
an ELF's symbol table has to be written before anyone asks for a name. This
lists the names to ask kl_vulkan_sym() about; the ones it does not know are
simply left out of the table.

Usage: gen_vk_names.py <vulkan include dir> > runtime/linux/kl_lx_vk_names.h
"""
import glob, os, re, sys

names = set()
for h in glob.glob(os.path.join(sys.argv[1], 'vulkan_*.h')):
    names.update(re.findall(r'VKAPI_CALL\s+(vk[A-Za-z0-9]+)\s*\(', open(h, errors='replace').read()))

print('// Generated by tools/gen_vk_names.py from the vendored Vulkan headers — do not edit.')
print('// %d commands.' % len(names))
for n in sorted(names):
    print('"%s",' % n)
